"""Clean-up safety net (MIGRATION_PLAN.md C0): the public-API scenarios of tests/golden/regression_cases.py,
run in a fresh process, must reproduce tests/golden/api_golden.npz exactly (NaN in the same places).
The golden data was generated by tests/golden/make_golden.py after checking it against the Fortran library.

Bit-identity also depends on the math library (glibc versions and the Windows UCRT differ in the last bits), so
this test is skipped on a platform other than the one recorded in the golden file; tests/test_reference.py
checks the results within tolerance everywhere."""
import os
import subprocess
import sys
from pathlib import Path

import numpy as np
import pytest

from conftest import same_reals

GOLDEN = Path(__file__).resolve().parent / 'golden'
sys.path.insert(0, str(GOLDEN))
from regression_cases import platform_tag, results  # noqa: E402


def test_public_api_matches_golden(tmp_path):
    golden = dict(np.load(GOLDEN / 'api_golden.npz'))
    if str(golden['__platform__']) != platform_tag():
        pytest.skip('golden results made on %s, this is %s (different math library)'
                    % (golden['__platform__'], platform_tag()))
    out = tmp_path / 'now.npz'
    env = dict(os.environ, PYTHONPATH=str(GOLDEN.parents[1]))
    subprocess.run([sys.executable, str(GOLDEN / 'regression_cases.py'), str(out)], check=True, env=env)
    now_all = dict(np.load(out))
    assert list(now_all['__unstable__']) == list(golden['__unstable__'])
    now, gold = results(now_all), results(golden)
    assert sorted(now) == sorted(gold)
    bad = [k for k in gold if not same_reals(now[k], gold[k])]
    assert not bad, bad
    assert sum(int(np.isnan(v).sum()) for v in gold.values()) > 0       # unconverged points are covered
